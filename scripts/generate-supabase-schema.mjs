import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import {
  createDatabase,
  dumpPublicSchema,
  prepareSupabaseDatabase,
  replayMigrations,
  startPostgres,
  stopPostgres,
} from './postgres-schema-tools.mjs';

const checkOnly = process.argv.includes('--check');
const unsupportedArgs = process.argv.slice(2).filter((arg) => arg !== '--check');
if (unsupportedArgs.length > 0) {
  throw new Error(`unsupported arguments: ${unsupportedArgs.join(', ')}`);
}

const schemaPath = new URL('../supabase/schema.sql', import.meta.url);
const header = `-- Generated fresh-install snapshot. Do not edit this file directly.
-- Source: supabase/migrations/*.sql in filename order on PostgreSQL 17.
-- Refresh: node scripts/generate-supabase-schema.mjs
-- Check: node scripts/generate-supabase-schema.mjs --check

CREATE EXTENSION IF NOT EXISTS pgcrypto;

`;

function buildRelationAclResetBlock(dump) {
  const tableNames = [...dump.matchAll(
    /^-- Name: TABLE ([a-z0-9_]+); Type: ACL; Schema: public; Owner: -$/gm,
  )].map((match) => match[1]);
  const sequenceNames = [...dump.matchAll(
    /^-- Name: SEQUENCE ([a-z0-9_]+); Type: ACL; Schema: public; Owner: -$/gm,
  )].map((match) => match[1]);
  const resets = [
    ...tableNames.map(
      (name) => `REVOKE ALL ON TABLE public.${name} FROM PUBLIC, anon, authenticated, service_role;`,
    ),
    ...sequenceNames.map(
      (name) => `REVOKE ALL ON SEQUENCE public.${name} FROM PUBLIC, anon, authenticated, service_role;`,
    ),
  ];
  if (resets.length === 0) throw new Error('generated dump contains no relation ACL targets');
  return `-- Normalize object ACLs independently of target-project default privileges.\n${resets.join('\n')}\n\n`;
}

function normalizeDump(dump) {
  let normalized = dump
    .replaceAll('\r\n', '\n')
    .split('\n')
    .filter((line) => !line.startsWith('\\restrict ') && !line.startsWith('\\unrestrict '))
    .filter((line) => !line.startsWith('-- Dumped from database version '))
    .filter((line) => !line.startsWith('-- Dumped by pg_dump version '))
    .join('\n')
    .replace('CREATE SCHEMA public;', 'CREATE SCHEMA IF NOT EXISTS public;')
    // pg_dump records revokes relative to its source database defaults. Make
    // service-only function ACLs safe when the target Supabase project still
    // grants new functions directly to Data API roles through default ACLs.
    .replace(
      /^REVOKE ALL ON FUNCTION (public\.[^;]+) FROM PUBLIC;$/gm,
      'REVOKE ALL ON FUNCTION $1 FROM PUBLIC, anon, authenticated, service_role;',
    )
    .trim();
  const firstAclSection = normalized.search(/^-- Name: (?:FUNCTION|TABLE|SEQUENCE) .+; Type: ACL;/m);
  if (firstAclSection < 0) throw new Error('generated dump contains no ACL section');
  const aclResetBlock = buildRelationAclResetBlock(normalized);
  normalized = `${normalized.slice(0, firstAclSection)}${aclResetBlock}${normalized.slice(firstAclSection)}`;
  return `${header}${normalized}\n`;
}

let containerName;
try {
  containerName = await startPostgres('voc-radar-schema-snapshot');
  createDatabase(containerName, 'snapshot_source');
  prepareSupabaseDatabase(containerName, 'snapshot_source', { preinstallPgcrypto: true });
  replayMigrations(containerName, 'snapshot_source');
  const generated = normalizeDump(dumpPublicSchema(containerName, 'snapshot_source'));

  if (checkOnly) {
    const current = readFileSync(schemaPath, 'utf8').replaceAll('\r\n', '\n');
    if (current !== generated) {
      console.error('[supabase-schema] OUTDATED: run node scripts/generate-supabase-schema.mjs');
      process.exitCode = 1;
    } else {
      console.log('[supabase-schema] OK');
    }
  } else {
    writeFileSync(schemaPath, generated);
    console.log('[supabase-schema] wrote supabase/schema.sql');
  }
} finally {
  if (containerName) stopPostgres(containerName);
}
